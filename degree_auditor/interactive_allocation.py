from __future__ import annotations

from pathlib import Path

from degree_auditor.allocation import UE_RESIDUAL_REQUIREMENT_ID
from degree_auditor.allocation_choices import (
    IGNORED_REQUIREMENT_ID,
    AllocationChoice,
    allocation_choices_for_course,
)
from degree_auditor.models import Allocation, AllocationRole, CourseAttempt, DegreeAuditConfig


def choices_for_transcript(
    config: DegreeAuditConfig,
    courses: list[CourseAttempt],
) -> dict[str, list[AllocationChoice]]:
    return {course.course_code: allocation_choices_for_course(config, course) for course in courses}


def allocations_for_selection(
    course: CourseAttempt,
    choices: list[AllocationChoice],
    selected_numbers: list[int],
) -> list[Allocation]:
    selected = [choices[number - 1] for number in selected_numbers]
    explicit = [
        choice
        for choice in selected
        if choice.requirement_id not in {UE_RESIDUAL_REQUIREMENT_ID, IGNORED_REQUIREMENT_ID}
    ]
    role = AllocationRole.double_count if len(explicit) > 1 else AllocationRole.primary
    allocations: list[Allocation] = []

    for choice in selected:
        if choice.requirement_id == UE_RESIDUAL_REQUIREMENT_ID:
            allocation_role = AllocationRole.residual_ue
        elif choice.requirement_id == IGNORED_REQUIREMENT_ID:
            allocation_role = AllocationRole.ignored
        else:
            allocation_role = role
        allocations.append(
            Allocation(
                course_code=course.effective_code,
                requirement_id=choice.requirement_id,
                units=course.units,
                allocation_role=allocation_role,
                manual=True,
            )
        )
    return allocations


def parse_selection(raw_value: str, choices: list[AllocationChoice]) -> list[int]:
    value = raw_value.strip()
    if not value:
        residual = _choice_number(choices, UE_RESIDUAL_REQUIREMENT_ID)
        ignored = _choice_number(choices, IGNORED_REQUIREMENT_ID)
        return [residual or ignored or 1]
    selected: list[int] = []
    for part in value.split(","):
        try:
            number = int(part.strip())
        except ValueError as exc:
            raise ValueError("Enter comma-separated choice numbers.") from exc
        if number < 1 or number > len(choices):
            raise ValueError(f"Choice {number} is outside the valid range 1-{len(choices)}.")
        if number not in selected:
            selected.append(number)
    return selected


def write_commented_allocation_yaml(
    path: Path,
    courses: list[CourseAttempt],
    choices_by_course: dict[str, list[AllocationChoice]],
    allocations_by_course: dict[str, list[Allocation]],
) -> None:
    lines = [
        "# Generated by degree-auditor interactive-allocate.",
        "# Eligibility comments list possible allocation targets shown during selection.",
        "allocations:",
    ]
    for course in courses:
        choices = choices_by_course[course.course_code]
        eligibility = ", ".join(choice.requirement_id for choice in choices) or "-"
        lines.append(f"  # {course.course_code} eligibility: {eligibility}")
        allocations = allocations_by_course.get(course.course_code, [])
        if not allocations:
            lines.append(f"  # {course.course_code}: no allocation selected")
        for allocation in allocations:
            lines.extend(_allocation_lines(allocation))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _allocation_lines(allocation: Allocation) -> list[str]:
    return [
        f"  - course_code: {allocation.course_code}",
        f"    requirement_id: {allocation.requirement_id}",
        f"    units: {allocation.units}",
        f"    allocation_role: {allocation.allocation_role.value}",
        f"    manual: {str(allocation.manual).lower()}",
    ]


def _choice_number(choices: list[AllocationChoice], requirement_id: str) -> int | None:
    for index, choice in enumerate(choices, start=1):
        if choice.requirement_id == requirement_id:
            return index
    return None
